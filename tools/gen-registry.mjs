#!/usr/bin/env node
// Generate the FX Rush effect registry from the vendored PixelFX tree.
//
//   node tools/gen-registry.mjs
//
// Discovers every effect file under third_party/pixelfx/src/fx/<category>/<name>.js (files starting with "_"
// are helpers), imports each one, reads its meta / act / exports, and writes:
//   src/fx/registry.gen.js      compact index the game and the FX lab load (id, category, timing, size, act)
//   docs/fx-registry.json       full dump (options, tags, act timing) for the coverage audit
// The upstream generated index (src/fx/index.js) is cross-checked so a re-sync can't silently drop effects.

import { readdirSync, statSync, writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PFX = join(ROOT, "third_party", "pixelfx");
const FX_DIR = join(PFX, "src", "fx");
const { actTiming, createFx, createFrame, clearFrame } = await import(pathToFileURL(join(PFX, "src", "core", "index.js")).href);

/**
 * Where an effect's mass sits relative to its origin (the brightness-weighted centroid over its life), so the
 * game can center an effect on a point whatever origin convention it uses (feet, floor, center).
 */
function focusOf(mod) {
  const m = mod.meta, [w, h] = m.size, [ox, oy] = m.origin, f = createFrame(w, h, 0, 0);
  const inst = createFx(mod, { x: ox, y: oy });
  const n = 12, D = m.duration ?? 1;
  let sx = 0, sy = 0, sw = 0;
  for (let i = 0; i < n; i++) {
    inst.update(i ? (D * (m.loop ? 1 : 0.7)) / n : 0.0001);
    clearFrame(f);
    inst.draw(f);
    for (let y = 0; y < h; y++)
      for (let x = 0; x < w; x++) {
        const j = y * w + x, c = f.color[j], l = f.light[j];
        const k = (c >>> 24 > 128 ? 1 : 0) + ((l & 255) + ((l >>> 8) & 255) + ((l >>> 16) & 255)) / 765;
        if (k <= 0) continue;
        sx += (x - ox) * k;
        sy += (y - oy) * k;
        sw += k;
      }
  }
  return sw ? [Math.round(sx / sw), Math.round(sy / sw)] : [0, 0];
}
const { categories } = await import(pathToFileURL(join(FX_DIR, "categories.js")).href);

const ids = [];
for (const cat of readdirSync(FX_DIR).sort()) {
  const d = join(FX_DIR, cat);
  if (cat.startsWith("_") || !statSync(d).isDirectory()) continue;
  for (const f of readdirSync(d).sort()) if (f.endsWith(".js") && !f.startsWith("_")) ids.push(`${cat}/${f.slice(0, -3)}`);
}

// the upstream index, for a cross-check
const upstreamIndex = readFileSync(join(FX_DIR, "index.js"), "utf8");
const upstreamIds = [...upstreamIndex.matchAll(/^\s+"([a-z]+\/[a-z0-9-]+)":/gm)].map((m) => m[1]);

const order = new Map(categories.map((c, i) => [c.id, i]));
ids.sort((a, b) => (order.get(a.split("/")[0]) ?? 99) - (order.get(b.split("/")[0]) ?? 99) || a.localeCompare(b));

const full = [], compact = [], errors = [];
for (const id of ids) {
  try {
    const mod = await import(pathToFileURL(join(FX_DIR, id + ".js")).href);
    const m = mod.meta;
    if (!m) throw new Error("no meta export");
    if (!mod.draw && !mod.create) throw new Error("exports neither draw nor create");
    const timing = actTiming(mod);
    const entry = {
      id,
      cat: id.split("/")[0],
      name: m.name,
      desc: m.desc,
      tags: m.tags ?? [],
      size: m.size,
      origin: m.origin,
      duration: +(m.duration ?? 1).toFixed(3),
      loop: !!m.loop,
      fps: m.fps ?? 30,
      actor: m.actor ? 2 : 0,
      kind: mod.create ? "sim" : "pure",
      back: !!mod.drawBack,
      actorAlpha: typeof mod.actorAlpha === "function",
      options: m.options ?? {},
      act: timing
        ? { windup: +timing.windup.toFixed(3), recovery: +timing.recovery.toFixed(3), onBody: timing.onBody, targets: timing.targets, hits: timing.hits.map((h) => ({ t: h.t, freeze: h.freeze, shake: h.shake, amp: h.amp })) }
        : null,
    };
    entry.focus = focusOf(mod);
    full.push(entry);
    compact.push([id, entry.loop ? 1 : 0, entry.duration, entry.size[0], entry.size[1], entry.origin[0], entry.origin[1], entry.actor, entry.act ? 1 : 0, entry.act?.onBody ? 1 : 0, entry.focus[0], entry.focus[1]]);
  } catch (e) {
    errors.push({ id, error: String(e?.message ?? e).split("\n")[0] });
  }
}

const missingFromUpstream = ids.filter((id) => !upstreamIds.includes(id));
const missingFiles = upstreamIds.filter((id) => !ids.includes(id));

const head = `// Generated by tools/gen-registry.mjs from third_party/pixelfx — do not edit; run \`npm run registry\`.
// Every PixelFX effect id with its timing and size:
// [id, loop, duration, w, h, originX, originY, actor, hasAct, onBody, focusX, focusY] (focus: the effect's visual
// center relative to its origin, measured by rendering it).
`;
const body = `export const CATEGORIES = ${JSON.stringify(categories.map((c) => ({ id: c.id, name: c.name })))};

export const FX_COUNT = ${compact.length};

export const FX_INDEX = [
${compact.map((r) => "  " + JSON.stringify(r)).join(",\n")},
];

/** id -> { id, cat, loop, duration, w, h, ox, oy, actor, act, onBody, fx, fy } */
export const FX = Object.fromEntries(
  FX_INDEX.map(([id, loop, duration, w, h, ox, oy, actor, act, onBody, fx, fy]) => [
    id,
    { id, cat: id.split("/")[0], loop: !!loop, duration, w, h, ox, oy, actor, act: !!act, onBody: !!onBody, fx, fy },
  ]),
);
`;
writeFileSync(join(ROOT, "src", "fx", "registry.gen.js"), head + "\n" + body);
mkdirSync(join(ROOT, "docs"), { recursive: true });
writeFileSync(
  join(ROOT, "docs", "fx-registry.json"),
  JSON.stringify({ upstream: "patch-gg/pixelfx", files: ids.length, upstreamIndex: upstreamIds.length, loaded: full.length, errors, missingFromUpstream, missingFiles, effects: full }, null, 1),
);

console.log(`effect files: ${ids.length}  upstream index: ${upstreamIds.length}  loaded: ${full.length}  errors: ${errors.length}`);
if (missingFromUpstream.length || missingFiles.length) console.log("index mismatch:", { missingFromUpstream, missingFiles });
for (const e of errors) console.log("  error", e.id, e.error);
console.log("-> src/fx/registry.gen.js, docs/fx-registry.json");
if (errors.length) process.exitCode = 1;
