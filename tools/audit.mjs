#!/usr/bin/env node
// PixelFX coverage audit for FX Rush.
//
//   node tools/audit.mjs            print the table, write docs/COVERAGE.md and docs/coverage.json
//
// Columns, per upstream effect id:
//   vendored   the effect file exists in third_party/pixelfx/src/fx (and in the upstream generated index)
//   loadable   it imports and exports meta + draw/create (docs/fx-registry.json from tools/gen-registry.mjs)
//   previewed  it passed the headless self-test (docs/fx-smoke.json from tools/fx-smoke.mjs: draws, stays inside
//              its canvas, ends / stops, frame cost)
//   wired      game code references the id (static scan of src/, excluding the registry, the usage notes and dev tools)
//   triggered  it actually reached the screen in recorded play sessions (docs/fx-runtime.json from tools/e2e.mjs)

import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));
const reg = read("docs/fx-registry.json");
const ids = reg.effects.map((e) => e.id);
const smoke = existsSync(join(ROOT, "docs/fx-smoke.json")) ? read("docs/fx-smoke.json") : null;
const runtime = existsSync(join(ROOT, "docs/fx-runtime.json")) ? read("docs/fx-runtime.json") : null;
const { USAGE } = await import("../src/fx/usage.js");

// every source file of the game
const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) {
      if (f !== "dev") walk(p);
    } else if (/\.(js|mjs)$/.test(f) && !/registry\.gen\.js$|usage\.js$/.test(f)) files.push(p);
  }
})(join(ROOT, "src"));
const where = new Map(ids.map((id) => [id, []]));
for (const f of files) {
  const src = readFileSync(f, "utf8");
  for (const id of ids) if (src.includes(`"${id}"`)) where.get(id).push(relative(ROOT, f).replace(/\\/g, "/"));
}

const smokeOf = new Map((smoke?.results ?? []).map((r) => [r.id, r]));
const trig = new Map(Object.entries(runtime?.used ?? {}));
const rows = ids.map((id) => {
  const s = smokeOf.get(id);
  return {
    id,
    cat: id.split("/")[0],
    vendored: existsSync(join(ROOT, "third_party/pixelfx/src/fx", id + ".js")),
    loadable: !reg.errors.some((e) => e.id === id),
    previewed: s ? s.status !== "fail" : null,
    preview: s?.status ?? "n/a",
    wired: where.get(id).length > 0,
    files: where.get(id),
    triggered: runtime ? (trig.get(id) ?? 0) : null,
    role: USAGE[id]?.role ?? "",
  };
});
const count = (f) => rows.filter(f).length;
const sum = {
  upstream: reg.upstreamIndex,
  files: reg.files,
  vendored: count((r) => r.vendored),
  loadable: count((r) => r.loadable),
  previewed: smoke ? count((r) => r.previewed) : "not run",
  previewWarn: smoke ? count((r) => r.preview === "warn") : "-",
  wired: count((r) => r.wired),
  triggered: runtime ? count((r) => r.triggered > 0) : "not run",
  runtimeSessions: runtime?.sessions ?? 0,
};
console.log(sum);
const missing = rows.filter((r) => !r.wired).map((r) => r.id);
const untriggered = runtime ? rows.filter((r) => r.wired && !(r.triggered > 0)).map((r) => r.id) : [];
if (missing.length) console.log("not wired:", missing.join(", "));
if (untriggered.length) console.log("wired but not seen in recorded play:", untriggered.join(", "));
const noRole = rows.filter((r) => !r.role).map((r) => r.id);
if (noRole.length) console.log("no role note:", noRole.length);

writeFileSync(join(ROOT, "docs/coverage.json"), JSON.stringify({ summary: sum, missing, untriggered, rows }, null, 1));
const md = [
  "# PixelFX coverage in FX Rush",
  "",
  "Generated by `npm run audit` (tools/audit.mjs). Upstream: patch-gg/pixelfx @ a841596.",
  "",
  "| measure | count |",
  "|---|---|",
  `| effects in upstream index | ${sum.upstream} |`,
  `| vendored files | ${sum.vendored} |`,
  `| loadable (meta + draw/create) | ${sum.loadable} |`,
  `| pass headless self-test (draws, in bounds, ends/stops) | ${sum.previewed}${smoke ? ` (${sum.previewWarn} with warnings)` : ""} |`,
  `| wired into game code | ${sum.wired} |`,
  `| seen on screen in recorded play (${sum.runtimeSessions} sessions) | ${sum.triggered} |`,
  "",
  missing.length ? `Not wired: ${missing.join(", ")}` : "Every upstream effect is wired into the game.",
  "",
  untriggered.length ? `Wired but not seen in the recorded sessions (rare branches): ${untriggered.join(", ")}` : "",
  "",
  "| effect | self-test | in game | times seen | role |",
  "|---|---|---|---|---|",
  ...rows.map((r) => `| \`${r.id}\` | ${r.preview} | ${r.wired ? "yes" : "**no**"} | ${r.triggered ?? "-"} | ${r.role.replace(/\|/g, "/")} |`),
  "",
];
writeFileSync(join(ROOT, "docs/COVERAGE.md"), md.join("\n"));
console.log("-> docs/COVERAGE.md, docs/coverage.json");
